// שביל כניסה: מהשער (z=15) עד המרפסת (z=6.2)
export const PATH = { x0: -1.1, x1: 1.1, z0: 6.2, z1: 15.2 };

// משטח חניה
export const DRIVEWAY = { x0: 3.2, x1: 6.4, z0: 9.0, z1: 15.2 };

// עצים: [x, z, קנה מידה]
export const TREES = [
  [-9.5, 8.5, 1.15], [-12.5, 2.0, 1.0], [-10.5, -6.5, 1.25], [-4.0, 10.5, 0.9],
  [9.5, 5.0, 1.1], [12.0, -3.0, 1.0], [8.5, -9.0, 1.2], [-13.0, -10.0, 0.95],
  [13.5, 10.5, 1.05], [-14.0, 11.0, 1.1],
];

// שיחים: [x, z, קנה מידה]
export const BUSHES = [
  [-2.6, 5.6, 1], [2.6, 5.6, 1], [-4.4, 5.2, 0.85], [4.6, 5.4, 0.8],
  [-6.8, 3.0, 0.9], [6.8, 1.5, 0.9], [-6.9, -2.5, 0.8], [6.9, -3.5, 0.85],
  [-2.0, -5.6, 0.8], [2.0, -5.6, 0.8], [5.0, -5.4, 0.9], [-5.0, -5.4, 0.9],
];

// עמודי תאורת גן: [x, z]
export const BOLLARDS = [
  [-1.6, 7.6], [1.6, 7.6], [-1.6, 11.2], [1.6, 11.2], [-1.6, 14.4], [1.6, 14.4],
];

// גדר היקפית (מלבן המגרש) עם פתח שער בחזית
export const PROPERTY = { minX: -16.5, maxX: 16.5, minZ: -13.5, maxZ: 15.5 };
export const GATE = { x0: -1.4, x1: 1.4 }; // פתח בגדר הדרומית (z = maxZ)

/** גופי התנגשות של החוץ */
export function exteriorColliders() {
  const list = [];
  const B = (x, y, z, sx, sy, sz) => list.push({ x, y, z, sx, sy, sz });
  const P = PROPERTY;
  const t = 0.3, h = 1.6;
  // גדר: ארבע צלעות, הדרומית מפוצלת סביב השער
  B((P.minX + GATE.x0) / 2, h / 2, P.maxZ, GATE.x0 - P.minX, h, t);
  B((GATE.x1 + P.maxX) / 2, h / 2, P.maxZ, P.maxX - GATE.x1, h, t);
  B(0, h / 2, P.minZ, P.maxX - P.minX, h, t);
  B(P.minX, h / 2, 0, t, h, P.maxZ - P.minZ);
  B(P.maxX, h / 2, 0, t, h, P.maxZ - P.minZ);
  // גזעי עצים
  for (const [x, z, s] of TREES) B(x, 1.5, z, 0.5 * s, 3, 0.5 * s);
  // שיחים (נמוכים — אפשר לראות מעליהם אבל לא לעבור)
  for (const [x, z, s] of BUSHES) B(x, 0.4, z, 1.0 * s, 0.8, 1.0 * s);
  // עמודי תאורה
  for (const [x, z] of BOLLARDS) B(x, 0.4, z, 0.18, 0.8, 0.18);
  return list;
}
